// node tests.cjs — PPH engine tests (extracts /*ENGINE-START*/…/*ENGINE-END*/ from index.html)
const fs=require('fs'),src=fs.readFileSync(__dirname+'/index.html','utf8');
const PPH=new Function(src.split('/*ENGINE-START*/')[1].split('/*ENGINE-END*/')[0]+';return PPH')();
let n=0,f=0;const t=(name,c)=>{n++;if(!c){f++;console.log('FAIL',name)}};
const e=(blood,hr,sbp,dbp)=>PPH.evaluate({blood,hr,sbp,dbp});
t('default case triggers',e(350,112,104,65).trigger);
t('≥300 + HR>100',e(300,101,120,80).trigger);
t('HR 100 is not >100',!e(300,100,120,80).trigger);
t('SI exactly 1 not >1',!e(300,100,100,70).signs.find(s=>s[0]==='SI >1')[1]);
t('SBP 100 not <100, DBP 60 not <60',!e(300,90,100,60).abnormal);
t('SBP 99 abnormal',e(300,90,99,60).trigger);
t('DBP 59 abnormal',e(300,90,110,59).trigger);
t('299 + abnormal no trigger',!e(299,130,90,50).trigger&&e(299,130,90,50).abnormal);
t('500 alone triggers',e(500,80,120,80).trigger&&e(500,80,120,80).reason==='失血量 ≥500 mL');
t('reason for 300 rule',e(320,108,120,80).reason.includes('300'));
t('RCOG minor',e(800,80,120,80).rcog.startsWith('minor'));
t('RCOG 1000 still minor',e(1000,80,120,80).rcog.startsWith('minor'));
t('RCOG major',e(1001,80,120,80).rcog.startsWith('major'));
t('no RCOG <500',e(400,80,120,80).rcog===null);
t('blank blood error',!e('',100,100,60).ok&&e('',100,100,60).errors[0].includes('失血量'));
t('implausible HR',!e(250,9999,100,60).ok);
t('implausible SBP',!e(250,90,3,1).ok);
t('dbp>=sbp',!e(300,90,80,80).ok);
t('negative blood',!e(-1,90,120,80).ok);
t('blood 0 ok',e(0,80,120,80).ok);

// drugPlan
const base={min:40,oxy:'none',txa:'0',txaOngoing:false,causes:{tone:true}};
const D=(o)=>PPH.drugPlan({...base,...o}),g=(r,id)=>r.items.find(i=>i.id===id);
t('oxy first-line rec',g(D({}),'oxy').st==='rec');
t('txa rec within 3h',g(D({}),'txa').st==='rec'&&D({}).txaLeft===140);
t('txa at 180 still rec',g(D({min:180}),'txa').st==='rec');
t('txa at 181 not started',g(D({min:181}),'txa').st==='na'&&D({min:181}).txaLeft===null);
t('txa vte avoid',g(D({vte:true}),'txa').st==='avoid');
t('txa 2nd dose after 3h allowed',g(D({min:300,txa:'1',txaOngoing:true}),'txa').st==='rec');
t('txa 1 dose no ongoing -> later',g(D({txa:'1'}),'txa').st==='later');
t('txa 2 doses done',g(D({txa:'2',txaOngoing:true}),'txa').st==='done');
t('renal note',g(D({renal:true}),'txa').why.some(w=>w.includes('腎')));
t('second-line later before oxy failure',['ergo','carbo','miso'].every(id=>g(D({}),id).st==='later'));
t('second-line rec after oxy inadequate',['ergo','carbo','miso'].every(id=>g(D({oxy:'inadequate'}),id).st==='rec'));
t('htn avoids ergo',g(D({oxy:'inadequate',htn:true}),'ergo').st==='avoid');
t('cyp contraindicates ergo',g(D({oxy:'inadequate',cyp:true}),'ergo').st==='contra');
t('cyp contra shown before oxy failure',g(D({cyp:true}),'ergo').st==='contra');
t('htn+cyp -> contra wins',g(D({oxy:'inadequate',htn:true,cyp:true}),'ergo').st==='contra'&&g(D({oxy:'inadequate',htn:true,cyp:true}),'ergo').why.length===2);
t('asthma avoids carbo',g(D({oxy:'inadequate',asthma:true}),'carbo').st==='avoid');
t('cardiac: carbo caution, ergo avoid',g(D({oxy:'inadequate',cardiac:true}),'carbo').st==='caution'&&g(D({oxy:'inadequate',cardiac:true}),'ergo').st==='avoid');
t('htn+asthma -> miso rec',g(D({oxy:'inadequate',htn:true,asthma:true}),'miso').st==='rec');
t('miso prophylaxis caution',g(D({oxy:'inadequate',misoProph:true}),'miso').st==='caution');
t('avoid shown even before oxy failure',g(D({asthma:true}),'carbo').st==='avoid');
t('oxy unavailable -> na',g(D({oxy:'unavailable'}),'oxy').st==='na');
t('trauma only: oxy consider + note',g(D({causes:{trauma:true}}),'oxy').st==='consider'&&D({causes:{trauma:true}}).notes.some(n=>n.t.startsWith('Trauma')));
t('trauma only: no second-line push',g(D({causes:{trauma:true},oxy:'inadequate'}),'ergo').st==='later');
t('no cause = treat as tone',g(D({causes:{}}),'oxy').st==='rec');
t('bad minutes',!D({min:''}).ok&&!D({min:-5}).ok);

// mind maps: structure, valid refs and jump targets, and figures agreeing with the engine
const MAPS=new Function(src.split('/*MAP-START*/')[1].split('/*MAP-END*/')[0]+';return MAPS')();
const leaves=m=>m.branches.flatMap(b=>b.k),all=[...leaves(MAPS.dx),...leaves(MAPS.tx)],has=(m,s)=>leaves(m).some(l=>l.t.includes(s));
t('two maps',Object.keys(MAPS).join()==='dx,tx');
t('map branches',Object.values(MAPS).every(m=>m.branches.length>=8&&m.branches.every(b=>b.k.length>=2&&/^#[0-9a-f]{6}$/.test(b.color))));
t('map refs exist on sources tab',all.every(l=>!l.r||l.r.every(n=>src.includes(`<b>[${n}] `))));
t('map jump targets exist',all.every(l=>!l.to||src.includes(`data-tab="${l.to}"`)||src.includes(`id="${l.to}"`)));
t('map tab wired',src.includes('data-tab="map"')&&src.includes('<section id="map"'));
t('map has all 4T',['Tone','Trauma','Tissue','Thrombin'].every(x=>MAPS.dx.branches.some(b=>b.t.startsWith(x))));
t('map thresholds match engine',has(MAPS.dx,'≥500 mL')&&e(500,80,120,80).trigger&&has(MAPS.dx,'≥300 mL')&&e(300,101,120,80).trigger&&['HR >100','SI >1','SBP <100','DBP <60'].every(s=>has(MAPS.dx,s)&&e(300,90,120,80).signs.some(z=>z[0]===s)));
t('map RCOG split matches engine',has(MAPS.dx,'500–1000 mL')&&has(MAPS.dx,'major >1000 mL')&&e(1000,80,120,80).rcog.includes('500–1000 mL'));
t('map TXA window matches engine',has(MAPS.tx,'出生後 3 小時內')&&g(D({min:180}),'txa').st==='rec'&&g(D({min:181}),'txa').st==='na');
const secondLine=D({oxy:'inadequate'});
t('map doses match engine',has(MAPS.tx,'10 IU IV')&&g(D({}),'oxy').dose.startsWith('10 IU IV')&&has(MAPS.tx,'1 g IV')&&g(D({}),'txa').dose.startsWith('1 g IV')&&has(MAPS.tx,'0.2 mg IM')&&g(secondLine,'ergo').dose.startsWith('0.2 mg IM')&&has(MAPS.tx,'250 μg IM')&&g(secondLine,'carbo').dose.startsWith('250 μg IM')&&has(MAPS.tx,'800 μg 舌下')&&g(secondLine,'miso').dose==='800 μg 舌下');
t('map avoid rules match engine',has(MAPS.tx,'禁止併用 ergot')&&g(D({oxy:'inadequate',cyp:true}),'ergo').st==='contra'&&has(MAPS.tx,'氣喘：避免 carboprost')&&g(D({oxy:'inadequate',asthma:true}),'carbo').st==='avoid'&&has(MAPS.tx,'抗纖溶禁忌：避免 TXA')&&g(D({vte:true}),'txa').st==='avoid');
console.log(`${n-f}/${n} passed`);process.exit(f?1:0);
